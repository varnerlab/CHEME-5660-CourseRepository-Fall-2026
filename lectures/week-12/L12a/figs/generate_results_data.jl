# Data for the two L12a results figures, from the same code and seed (5660) as the examples, so
# every plotted point matches the notebooks. Run from this folder:
#   julia --project=../../../.. generate_results_data.jl
using VLQuantitativeFinancePackage, Random, Statistics, Printf

writecsv(name, header, rows) = open(name, "w") do io
    println(io, header)
    for r ∈ rows; println(io, join([@sprintf("%.6f", x) for x ∈ r], ",")); end
end
random_seed = 5660

# ---------- thermal minority game example, Tasks 2 and 3 ----------
m = 6; P = 2^m; S = 2; N_crowded = 641; number_of_rounds = 10_000; burn_in = 2_000; number_of_seeds = 3
agent_counts = [21, 41, 61, 81, 101, 121, 141, 151:10:251..., 281, 321, 401, 501, 641, 801, 1001]
rng = MersenneTwister(random_seed); phase = []
for N ∈ agent_counts, k ∈ 1:number_of_seeds
    r = solve(build(MyThermalMinorityGameModel, (N = N, m = m, S = S, temperature = 0.0, rng = rng));
        number_of_rounds = number_of_rounds, burn_in = burn_in, rng = rng)
    push!(phase, (N, r.alpha, r.volatility_per_agent))
end
temperatures = [0.0; 10.0 .^ range(-2, 5, length = 15); Inf]
rng = MersenneTwister(random_seed); temps = []
for T ∈ temperatures, k ∈ 1:number_of_seeds
    r = solve(build(MyThermalMinorityGameModel, (N = N_crowded, m = m, S = S, temperature = T, rng = rng));
        number_of_rounds = number_of_rounds, burn_in = burn_in, rng = rng)
    push!(temps, (T, r.volatility_per_agent))
end
writecsv("Data-L12a-MG-Phase-Games.csv", "alpha,volatility", [(a, v) for (_, a, v) ∈ phase])
pm = [(P / N, mean(x[3] for x ∈ phase if x[1] == N)) for N ∈ sort(agent_counts, rev = true)]
writecsv("Data-L12a-MG-Phase-Means.csv", "alpha,volatility", pm)
writecsv("Data-L12a-MG-Temperature-Games.csv", "temperature,volatility", [(T, v) for (T, v) ∈ temps if 0 < T < Inf])
finite = filter(T -> 0 < T < Inf, temperatures)
writecsv("Data-L12a-MG-Temperature-Means.csv", "temperature,volatility", [(T, mean(v for (t, v) ∈ temps if t == T)) for T ∈ finite])
greedy = mean(v for (t, v) ∈ temps if t == 0.0); randomchoice = mean(v for (t, v) ∈ temps if isinf(t))
jmin = argmin(last.(pm))

# ---------- Farmer–Joshi example, Tasks 1 to 3 ----------
σ_ξ = 0.05; σ_η = 0.01; number_of_steps = 20_000; fj_burn = 2_000
excess_kurtosis(x) = mean(((x .- mean(x)) ./ std(x, corrected = false)).^4) - 3
rng = MersenneTwister(random_seed); markets = Dict{String,Any}()
groups = Dict("value investors only" => (trend_number = 0,), "trend followers only" => (value_number = 0,), "both groups" => NamedTuple())
for name ∈ ["value investors only", "trend followers only", "both groups"]
    model = build(MyFarmerJoshiMarketModel, merge(groups[name], (σ_ξ = σ_ξ, σ_η = σ_η, rng = rng)))
    markets[name] = solve(model; number_of_steps = number_of_steps, burn_in = fj_burn, rng = rng)
end
r = markets["both groups"].returns
prices = MyTrainingMarketDataSet()["dataset"]["SPY"].close
g = (252) .* diff(log.(prices))
lags = collect(1:50)
writecsv("Data-L12a-FJ-ACF.csv", "lag,model,spy", [(l, a, b) for (l, a, b) ∈ zip(lags, sample_autocorrelation(abs.(r), lags), sample_autocorrelation(abs.(g), lags))])
trend_counts = [0, 300, 600, 900, 1_200, 1_500]
rng = MersenneTwister(random_seed); mix = []
for n ∈ trend_counts, k ∈ 1:3
    rr = solve(build(MyFarmerJoshiMarketModel, (trend_number = n, σ_ξ = σ_ξ, σ_η = σ_η, rng = rng));
        number_of_steps = number_of_steps, burn_in = fj_burn, rng = rng).returns
    push!(mix, (n, sample_autocorrelation(rr, [1])[1], excess_kurtosis(rr)))
end
writecsv("Data-L12a-FJ-Mix-Games.csv", "trend,acf1,kurtosis", mix)
writecsv("Data-L12a-FJ-Mix-Means.csv", "trend,acf1,kurtosis",
    [(n, mean(x[2] for x ∈ mix if x[1] == n), mean(x[3] for x ∈ mix if x[1] == n)) for n ∈ trend_counts])

open("Data-L12a-Values.tex", "w") do io
    @printf(io, "%% generated by generate_results_data.jl (seed %d)\n", random_seed)
    @printf(io, "\\def\\mggreedy{%.4f}\n\\def\\mgrandom{%.4f}\n\\def\\mgminalpha{%.4f}\n\\def\\mgminvol{%.4f}\n", greedy, randomchoice, pm[jmin]...)
    @printf(io, "\\def\\spykurt{%.4f}\n\\def\\spyacf{%.4f}\n\\def\\fjband{%.4f}\n\\def\\spyband{%.4f}\n",
        excess_kurtosis(g), sample_autocorrelation(g, [1])[1], 1.96 / sqrt(length(r)), 1.96 / sqrt(length(g)))
end
@printf("MG: greedy %.3f random %.3f min %.3f at %.4f | FJ: kurt %.3f acf1 %.3f |r|1 %.3f | SPY kurt %.3f acf %.3f\n",
    greedy, randomchoice, pm[jmin][2], pm[jmin][1], excess_kurtosis(r), sample_autocorrelation(r, [1])[1],
    sample_autocorrelation(abs.(r), [1])[1], excess_kurtosis(g), sample_autocorrelation(g, [1])[1])
